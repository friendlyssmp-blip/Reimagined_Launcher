const dict: Record<AppLanguage, Record<string, string>> = { en, es, fr }

let lang: AppLanguage = 'en'
const listeners = new Set<() => void>()

export function setLanguage(l: AppLanguage): void {
  lang = l
  listeners.forEach((f) => f())
}

export function getLanguage(): AppLanguage {
  return lang
}

export function subscribeLanguage(f: () => void): () => void {
  listeners.add(f)
  return () => listeners.delete(f)
}

/** Translate a key; falls back to English, then to the raw key. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  }
  return s
}

/** React hook — re-renders on language change. */
export function useT(): typeof t {
  useSyncExternalStore(subscribeLanguage, getLanguage, getLanguage)
  return t
}
